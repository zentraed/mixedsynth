"""
Densified Clifford+T candidate harvesting for each Rz channel.

Wraps genlist._sweep_candidate_set_mp to get n_keep candidates per T-level,
then returns (t_count, U_mp) pairs for use in the optimizer.

T=0 and T=1 support
-------------------
The Python gridsynth port only returns sequences with T ≥ 2.  The original
Haskell gridsynth handles k=0/k=1 lattice points (T-count = 0 via the relation
tcount(k) = max(0, 2k-2)) and T=1 circuits from the phase-sensitive branch.

To fill this gap, harvest_rz explicitly prepends T=0 and T=1 candidates:

  T=0 : the nearest Clifford(s) to Rz(angle), computed by searching all 192
        single-qubit Clifford U(2) matrices (generated by H and S as U(2)
        matrices; 24 distinct gates × 8 global phases).  The strip_phase step
        in generators.rotation_vector collapses these to 24 unique rotation
        vectors automatically.

  T=1 : circuits of the form C·T where C is any Clifford and T = diag(1, e^{iπ/4}).
        This set of 192 unitaries covers all T=1 Rz approximations (the right-
        Clifford factor C2 in C1·T·C2 adds no new distinct rotation vectors
        because strip_phase is invariant under right-Clifford multiplication up
        to SU(2) equivalence; confirmed numerically above).
"""

import hashlib
import random

import gmpy2
import numpy as np
import mpmath as mp


from mixedsynth.genlist import _sweep_candidate_set_mp, _gmpy2_local
from mixedsynth.sequences import tokenize, t_count as _seq_t_count

# ---------------------------------------------------------------------------
# Pre-computed Clifford group (T=0) and T-gate coset (T=1)
# ---------------------------------------------------------------------------

def _build_clifford_group():
    """
    Generate the single-qubit Clifford group as U(2) matrices (192 elements:
    24 distinct gates × 8 global-phase variants from the ω-based generators).

    Returns (matrices, sequences): index-matched lists, where sequences[i] is
    a gate string in *matrix order* (same convention as genlist /
    exact_decomp_to_matrix_string): "HS" means the matrix H @ S.  The
    identity is the empty string.
    """
    H = np.array([[1, 1], [1, -1]], dtype=complex) / np.sqrt(2)
    S = np.array([[1, 0], [0, 1j]], dtype=complex)

    def key(M):
        return tuple(np.round(M.flat, 8))

    seen = {}
    queue = [(np.eye(2, dtype=complex), "")]
    while queue:
        M, s = queue.pop(0)
        k = key(M)
        if k in seen:
            continue
        seen[k] = (M.copy(), s)
        for G, g in [(H, "H"), (S, "S")]:
            for P, ps in [(G @ M, g + s), (M @ G, s + g)]:
                pk = key(P)
                if pk not in seen:
                    queue.append((P, ps))
    entries = list(seen.values())
    return [M for M, _ in entries], [s for _, s in entries]


# Module-level cache (built once on first call)
_CLIFFORDS = None
_CLIFFORD_SEQS = None
_T1_CIRCUITS = None
_T1_SEQS = None


def _get_cliffords():
    global _CLIFFORDS, _CLIFFORD_SEQS
    if _CLIFFORDS is None:
        _CLIFFORDS, _CLIFFORD_SEQS = _build_clifford_group()
    return _CLIFFORDS


def _get_clifford_seqs():
    _get_cliffords()
    return _CLIFFORD_SEQS


def _get_t1_circuits():
    """C·T for each Clifford C — all distinct T=1 unitaries (192 circuits)."""
    global _T1_CIRCUITS, _T1_SEQS
    if _T1_CIRCUITS is None:
        T = np.array([[1, 0], [0, np.exp(1j * np.pi / 4)]], dtype=complex)
        _T1_CIRCUITS = [C @ T for C in _get_cliffords()]
        _T1_SEQS = [s + "T" for s in _get_clifford_seqs()]
    return _T1_CIRCUITS


def _get_t1_seqs():
    _get_t1_circuits()
    return _T1_SEQS


def _seq_to_mp(seq, dps):
    """
    Exact Clifford+T matrix of a matrix-order H/S/T string as an mpmath
    matrix at dps + 10 digits (built from the exact gate entries, not from
    the float64 BFS matrices, so the result does not depend on platform
    floating-point details).
    """
    with mp.workdps(dps + 10):
        r = 1 / mp.sqrt(2)
        gates = {
            "H": mp.matrix([[r, r], [r, -r]]),
            "S": mp.matrix([[1, 0], [0, mp.j]]),
            "T": mp.matrix([[1, 0], [0, mp.expjpi(mp.mpf(1) / 4)]]),
        }
        M = mp.eye(2)
        for g in seq:
            M = M * gates[g]
        return M


# Exact low-T matrices, cached per (t_target, dps).
_LOW_T_MP = {}


def _low_t_matrices_mp(t_target, dps):
    key = (t_target, dps)
    if key not in _LOW_T_MP:
        seqs = _get_clifford_seqs() if t_target == 0 else _get_t1_seqs()
        _LOW_T_MP[key] = [_seq_to_mp(s, dps) for s in seqs]
    return _LOW_T_MP[key]


def _phase_free_key(U, scale):
    """
    Hashable key of U up to global phase: rotate the first entry of modulus
    > 1/4 onto the positive reals and round every entry to 1/scale.
    Caller sets mp.workdps.
    """
    flat = [U[0, 0], U[0, 1], U[1, 0], U[1, 1]]
    a = next(x for x in flat if abs(x) > 0.25)
    ph = abs(a) / a
    return tuple((int(mp.nint((x * ph).real * scale)),
                  int(mp.nint((x * ph).imag * scale))) for x in flat)


def _low_t_approx_mp(angle, t_target, n_keep, dps, with_sequences=False):
    """
    Return up to n_keep (t_count, U_mp) pairs for T=0 or T=1
    ((t_count, seq, U_mp) triples if with_sequences=True).

    t_target : 0 — return nearest Clifford(s)
               1 — return nearest C·T circuit(s)

    Candidates are the n_keep distinct gates (up to global phase) of highest
    fidelity |Tr(Rz(angle)† · U)|²/4, in descending fidelity.  The 8
    global-phase variants of each gate are collapsed to one, so the n_keep
    slots are filled with genuinely distinct gates.

    Exactness and determinism
    -------------------------
    Matrices and fidelities are computed in mpmath from the exact gate
    entries.  Distinct gates often have exactly equal fidelity (for
    Rz(φ+5π/2) with φ=2.3 at T=1, e.g. S†HT and SHSHT); such ties, and the
    choice of word among phase variants, are broken by the fixed Clifford
    enumeration order (shortest word first).  Earlier versions scored in
    float64 and deduplicated by fidelity rounded to 8 decimals, which
    (a) also discarded distinct gates that tie in fidelity and (b) chose
    the survivor by last-ulp rounding noise, so the harvest depended on the
    platform / numpy build.
    """
    assert t_target in (0, 1), "t_target must be 0 or 1"

    seqs = _get_clifford_seqs() if t_target == 0 else _get_t1_seqs()
    mats = _low_t_matrices_mp(t_target, dps)
    with mp.workdps(dps + 10):
        tH = rz_exact_mp(angle, dps).H
        # Round to ~half the working precision: values equal in exact
        # arithmetic compare equal; genuine differences survive.
        scale = mp.mpf(10) ** ((dps + 10) // 2)
        scored = []
        for i, U in enumerate(mats):
            tr = tH[0, 0] * U[0, 0] + tH[1, 1] * U[1, 1]   # Rz is diagonal
            fe_key = int(mp.nint(abs(tr) ** 2 / 4 * scale))
            scored.append((-fe_key, i, _phase_free_key(U, scale)))
    scored.sort()

    result = []
    seen_gates = set()
    for _neg_fe, idx, gate_key in scored:
        if len(result) >= n_keep:
            break
        if gate_key in seen_gates:     # global-phase variant of a kept gate
            continue
        seen_gates.add(gate_key)
        U_mp = mats[idx].copy()
        if with_sequences:
            result.append((t_target, seqs[idx], U_mp))
        else:
            result.append((t_target, U_mp))

    return result


