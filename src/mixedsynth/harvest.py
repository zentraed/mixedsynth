def rz_angles_for_u3(theta, phi, lam):
    """
    Return the three Rz angles for U3(θ,φ,λ) = Rz(φ+5π/2)·H·Rz(θ)·H·Rz(λ−π/2).
      angle[0] → Rz(λ−π/2)     (rightmost, labelled rz1)
      angle[1] → Rz(θ)          (middle,    labelled rz2)
      angle[2] → Rz(φ+5π/2)    (leftmost,  labelled rz3)
    """
    return (lam - np.pi / 2, theta, phi + 5 * np.pi / 2)


def rz_exact_mp(angle, dps=60):
    """Exact Rz(angle) as an mpmath 2×2 matrix."""
    with mp.workdps(dps + 10):
        h = mp.mpf(angle) / 2
        return mp.matrix([
            [mp.exp(-mp.j * h), mp.mpf(0)],
            [mp.mpf(0),         mp.exp(mp.j * h)],
        ])


def harvest_rz(angle, t_min=0, t_budget=50, n_keep=5, stride=1, dps=60,
               with_sequences=False):
    """
    Harvest Clifford+T approximations of Rz(angle) within a T-gate budget.

    angle     : Rz rotation angle (float, radians)
    t_min     : minimum T-gate count
    t_budget  : maximum T-gate count
    n_keep    : candidates kept per T-level (diversity source)
    stride    : step between T levels (from T=t_min up to T=t_budget)
    dps       : mpmath decimal places for matrix entries
    with_sequences : if True, also return the Clifford+T gate string of each
                candidate (matrix order, tokens H S Sd X Y Z T)

    Returns list of (t_count: int, U_mp: mpmath 2×2 matrix), sorted by t_count,
    or (t_count, seq: str, U_mp) triples when with_sequences=True.

    T=0 and T=1 notes
    -----------------
    The Python gridsynth port only generates sequences with T ≥ 2.  When
    t_min ≤ 0 or t_min ≤ 1, this function prepends explicit T=0 (nearest
    Clifford) and T=1 (nearest C·T circuit) candidates before the gridsynth
    sweep.  The sweep starts from max(t_min, 2) to avoid duplicating effort.
    """
    members = []

    # ---- T=0 candidates (nearest Clifford) ----
    if t_min <= 0 <= t_budget:
        members.extend(_low_t_approx_mp(angle, 0, n_keep, dps, with_sequences))

    # ---- T=1 candidates (nearest C·T circuits) ----
    if t_min <= 1 <= t_budget:
        members.extend(_low_t_approx_mp(angle, 1, n_keep, dps, with_sequences))

    # ---- gridsynth sweep (T ≥ 2) ----
    gs_t_min = max(t_min, 2)
    if gs_t_min <= t_budget:
        raw = _sweep_candidate_set_mp(
            angle, gs_t_min, t_budget,
            n_cands_per_level=n_keep,
            t_step=stride,
            dps=dps,
        )
        if with_sequences:
            members.extend(raw)
        else:
            members.extend((t, U) for (t, _seq, U) in raw)

    # Sort by T ascending (T=0 and T=1 are already first)
    members.sort(key=lambda x: x[0])
    return members
