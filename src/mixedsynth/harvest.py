"""
Densified Clifford+T candidate harvesting for each Rz channel.

Wraps genlist._sweep_candidate_set_mp to get n_keep candidates per T-level,
then returns (t_count, U_mp) pairs for use in the optimizer.

T=0 and T=1 support
-------------------
The Python gridsynth port only returns sequences with T ≥ 2.  The original
Haskell gridsynth handles k=0/k=1 lattice points (T-count = 0 via the relation
tcount(k) = max(0, 2k-2)) and T=1 circuits from the phase-sensitive branch.

To fill this gap, harvest_rz explicitly prepends T=0 and T=1 candidates:

  T=0 : the nearest Clifford(s) to Rz(angle), computed by searching all 192
        single-qubit Clifford U(2) matrices (generated by H and S as U(2)
        matrices; 24 distinct gates × 8 global phases).  The strip_phase step
        in generators.rotation_vector collapses these to 24 unique rotation
        vectors automatically.

  T=1 : circuits of the form C·T where C is any Clifford and T = diag(1, e^{iπ/4}).
        This set of 192 unitaries covers all T=1 Rz approximations (the right-
        Clifford factor C2 in C1·T·C2 adds no new distinct rotation vectors
        because strip_phase is invariant under right-Clifford multiplication up
        to SU(2) equivalence; confirmed numerically above).
"""

import numpy as np
import mpmath as mp


from mixedsynth.genlist import _sweep_candidate_set_mp

# ---------------------------------------------------------------------------
# Pre-computed Clifford group (T=0) and T-gate coset (T=1)
# ---------------------------------------------------------------------------

def _build_clifford_group():
    """
    Generate the single-qubit Clifford group as U(2) matrices (192 elements:
    24 distinct gates × 8 global-phase variants from the ω-based generators).

    Returns (matrices, sequences): index-matched lists, where sequences[i] is
    a gate string in *matrix order* (same convention as genlist /
    exact_decomp_to_matrix_string): "HS" means the matrix H @ S.  The
    identity is the empty string.
    """
    H = np.array([[1, 1], [1, -1]], dtype=complex) / np.sqrt(2)
    S = np.array([[1, 0], [0, 1j]], dtype=complex)

    def key(M):
        return tuple(np.round(M.flat, 8))

    seen = {}
    queue = [(np.eye(2, dtype=complex), "")]
    while queue:
        M, s = queue.pop(0)
        k = key(M)
        if k in seen:
            continue
        seen[k] = (M.copy(), s)
        for G, g in [(H, "H"), (S, "S")]:
            for P, ps in [(G @ M, g + s), (M @ G, s + g)]:
                pk = key(P)
                if pk not in seen:
                    queue.append((P, ps))
    entries = list(seen.values())
    return [M for M, _ in entries], [s for _, s in entries]


# Module-level cache (built once on first call)
_CLIFFORDS = None
_CLIFFORD_SEQS = None
_T1_CIRCUITS = None
_T1_SEQS = None


def _get_cliffords():
    global _CLIFFORDS, _CLIFFORD_SEQS
    if _CLIFFORDS is None:
        _CLIFFORDS, _CLIFFORD_SEQS = _build_clifford_group()
    return _CLIFFORDS


def _get_clifford_seqs():
    _get_cliffords()
    return _CLIFFORD_SEQS


def _get_t1_circuits():
    """C·T for each Clifford C — all distinct T=1 unitaries (192 circuits)."""
    global _T1_CIRCUITS, _T1_SEQS
    if _T1_CIRCUITS is None:
        T = np.array([[1, 0], [0, np.exp(1j * np.pi / 4)]], dtype=complex)
        _T1_CIRCUITS = [C @ T for C in _get_cliffords()]
        _T1_SEQS = [s + "T" for s in _get_clifford_seqs()]
    return _T1_CIRCUITS


def _get_t1_seqs():
    _get_t1_circuits()
    return _T1_SEQS


def _np_to_mp(M_np, dps):
    """Convert a 2×2 numpy complex array to an mpmath matrix."""
    with mp.workdps(dps + 10):
        return mp.matrix([
            [mp.mpc(str(float(M_np[i, j].real)), str(float(M_np[i, j].imag)))
             for j in range(2)]
            for i in range(2)
        ])


def _low_t_approx_mp(angle, t_target, n_keep, dps, with_sequences=False):
    """
    Return up to n_keep (t_count, U_mp) pairs for T=0 or T=1
    ((t_count, seq, U_mp) triples if with_sequences=True).

    t_target : 0 — return nearest Clifford(s)
               1 — return nearest C·T circuit(s)

    Candidates are sorted by descending fidelity |Tr(Rz(angle)† · U)|²/4.
    Global-phase variants of the same gate have identical fidelity AND will
    produce identical rotation vectors via strip_phase; they are deduplicated
    here so that the n_keep slots are filled with genuinely distinct gates
    (distinct rounded fidelity values → distinct SU(2) orbits).
    """
    assert t_target in (0, 1), "t_target must be 0 or 1"

    rz_np = np.array(
        [[np.exp(-1j * angle / 2), 0.0], [0.0, np.exp(1j * angle / 2)]],
        dtype=complex,
    )
    tH = rz_np.conj().T

    circuits = _get_cliffords() if t_target == 0 else _get_t1_circuits()
    seqs = _get_clifford_seqs() if t_target == 0 else _get_t1_seqs()
    scored = [(abs(np.trace(tH @ U)) ** 2 / 4, i) for i, U in enumerate(circuits)]
    scored.sort(key=lambda x: -x[0])

    result = []
    seen_fidelities = set()
    for fe, idx in scored:
        if len(result) >= n_keep:
            break
        # Deduplicate: global-phase variants all have the same rounded fidelity
        fe_key = round(fe, 8)
        if fe_key in seen_fidelities:
            continue
        seen_fidelities.add(fe_key)
        U_mp = _np_to_mp(circuits[idx], dps)
        if with_sequences:
            result.append((t_target, seqs[idx], U_mp))
        else:
            result.append((t_target, U_mp))

    return result


